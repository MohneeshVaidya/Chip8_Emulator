bool load_rom(State *state, const char *path) {
    FILE *file = fopen(path, "rb");
    if (!file) {
        SDL_Log("not able to open : %s\n", path);
        return false;
    }

    fseek(file, 0, SEEK_END);
    size_t size = ftell(file);
    rewind(file);

    if (fread(state->memory + PROG_START, sizeof(uint8_t), size, file) < size) {
        SDL_Log("not able to read file : %s\n", path);
        fclose(file);
        return false;
    }

    fclose(file);

    state->pc = PROG_START;

    return true;
}
